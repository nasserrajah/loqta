const fs = require('fs');
const Database = require('./node_modules/better-sqlite3');
const db = new Database('./apps/api/data/loqta.db', { readonly: true });
const T = db.prepare("SELECT sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' AND name != 'schema_migrations'").all();
const I = db.prepare("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL").all();
let s = 'PRAGMA foreign_keys = ON;' + String.fromCharCode(10,10);
T.forEach(t => { s += t.sql + ';' + String.fromCharCode(10,10); });
I.forEach(i => { s += i.sql + ';' + String.fromCharCode(10); });
fs.mkdirSync('./database/migrations', { recursive: true });
fs.writeFileSync('./database/migrations/000_initial.sql', s, 'utf8');
console.log('Written. Tables=' + T.length + ' Indexes=' + I.length);
db.close();
