export type Language = 'en' | 'ar';
export type TranslationKey = keyof typeof dictionary.en;

/** Helper to pick localized field */
export function pickLocalized<T>(
  language: Language,
  en: T,
  ar?: T
): T {
  return language === 'ar' && ar !== undefined && ar !== null && (ar as any) !== '' ? ar : en;
}